def parse_float_or_fraction(value: str) -> float:
    value = value.strip()

    if "/" in value:
        return float(Fraction(value))

    return float(value)


def parse_epsilon_list(value: str):
    """
    Example:
        "0.1,0.5,1.0,2.0"
    """
    return [float(v.strip()) for v in value.split(",") if v.strip()]


def parse_epsilon_alloc(value: str):
    """
    Expected order:
        ag,td,markov,mle

    Example:
        "1/9,3/9,4/9,1/9"
        "0.111111,0.333333,0.444444,0.111111"
    """
    parts = [p.strip() for p in value.split(",") if p.strip()]

    if len(parts) != 4:
        raise ValueError(
            "--epsilon-alloc must contain 4 values: ag,td,markov,mle"
        )

    parsed = [parse_float_or_fraction(p) for p in parts]

    total = sum(parsed)
    if abs(total - 1.0) > 1e-6:
        raise ValueError(
            f"--epsilon-alloc must sum to 1.0, but got {total}"
        )

    return {
        "ag": parsed[0],
        "td": parsed[1],
        "markov": parsed[2],
        "mle": parsed[3],
    }


def count_prepared_trajectories():
    """
    Reads the prepared DP-Star trajectory-name pickle.

    This should normally match the number of trajectories generated by
    prepare_dpstar_dataset.py.
    """
    name_list_path = BASE_DIR / "data" / USE_DATA / "trajs_file_name_list.pkl"

    if not name_list_path.exists():
        return None

    with name_list_path.open("rb") as f:
        names = pickle.load(f)

    return len(names)


def parse_args():
    parser = argparse.ArgumentParser(
        description="Run DP-Star with command-line parameters."
    )

    parser.add_argument(
        "--epsilons",
        default=",".join(str(e) for e in epsilon_list),
        help="Comma-separated epsilon values, e.g. 0.1,0.5,1.0,2.0.",
    )

    parser.add_argument(
        "--n-top-grid",
        type=int,
        default=n_top_grid,
        help="Top-grid size for DP-Star adaptive grid. Default comes from config.py.",
    )

    parser.add_argument(
        "--beta-factor",
        type=float,
        default=beta_factor,
        help="DP-Star adaptive-grid beta factor. Smaller value creates more bottom grids.",
    )

    parser.add_argument(
        "--epsilon-alloc",
        default=",".join(str(epsilon_alloc[k]) for k in ["ag", "td", "markov", "mle"]),
        help="Budget allocation as ag,td,markov,mle. Example: 1/9,3/9,4/9,1/9.",
    )

    parser.add_argument(
        "--synthetic-count",
        type=int,
        default=None,
        help=(
            "Number of synthetic trajectories to generate. "
            "Default: number from trajs_file_name_list.pkl, then fallback to TRAJS_NUM[USE_DATA]."
        ),
    )

    parser.add_argument(
        "--mapping-rate",
        type=float,
        default=MDL_SCALING_RATE[USE_DATA],
        help=(
            "MDL scaling/mapping rate used to convert synthetic MDL coordinates back to GPS. "
            "Must match prepare_dpstar_dataset.py --scaling-rate."
        ),
    )

    return parser.parse_args()


