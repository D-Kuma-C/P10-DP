def run(epsilon, run_config):
    middleware_dir = BASE_DIR / "data" / USE_DATA / "Middleware"
    sd_dir = BASE_DIR / "data" / USE_DATA / "SD"

    middleware_dir.mkdir(parents=True, exist_ok=True)
    sd_dir.mkdir(parents=True, exist_ok=True)

    alloc = run_config["epsilon_alloc"]

    # generate adaptive grid
    n_grid = generate_adaptive_grid(
        mdl_trajs_dir=mdl_trajs_path.format(USE_DATA),
        top_grid_path=top_grid_path.format(USE_DATA, epsilon),
        grid_trajs_path=grid_trajs_path.format(USE_DATA, epsilon),
        grid_block_gps_range_path=grid_block_gps_range_path.format(USE_DATA, epsilon),
        n_top_grid=run_config["n_top_grid"],
        epsilon_alloc=alloc["ag"] * epsilon,
        epsilon_total=epsilon,
        gps_range=gps_range,
        beta_factor=run_config["beta_factor"],
    )

    trip_distribution_main(
        n_grid,
        _epsilon=alloc["td"] * epsilon,
        grid_trajs_path=grid_trajs_path.format(USE_DATA, epsilon),
        trip_distribution_path=trip_distribution_path.format(USE_DATA, epsilon),
    )

    mobility_model_main(
        n_grid,
        _epsilon=alloc["markov"] * epsilon,
        grid_trajs_path=grid_trajs_path.format(USE_DATA, epsilon),
        midpoint_movement_path=midpoint_movement_path.format(USE_DATA, epsilon),
    )

    maxT = route_length_estimate_main(
        n_grid,
        _epsilon=alloc["mle"] * epsilon,
        grid_trajs_path=grid_trajs_path.format(USE_DATA, epsilon),
        routes_length_path=length_traj_path.format(USE_DATA, epsilon),
    )

    synthetic_trajs(
        n_grid,
        maxT,
        trip_distribution_path.format(USE_DATA, epsilon),
        midpoint_movement_path.format(USE_DATA, epsilon),
        length_traj_path.format(USE_DATA, epsilon),
        sd_path.format(USE_DATA, epsilon),
        run_config["synthetic_count"],
    )

    generate_sd_grid_mapping_traj(
        sd_path=sd_path.format(USE_DATA, epsilon),
        grid_block_gps_range_path=grid_block_gps_range_path.format(USE_DATA, epsilon),
        sd_final_path=sd_final_path.format(USE_DATA, epsilon),
        mapping_rate=run_config["mapping_rate"],
        mapping_bias=mapping_bias,
    )


