    print(f"beta_factor = {run_config['beta_factor']}")
    print(f"epsilon_alloc = {run_config['epsilon_alloc']}")
    print(f"synthetic_count = {run_config['synthetic_count']}")
    print(f"mapping_rate = {run_config['mapping_rate']}")
    print(f"gps_range = {gps_range}")
    print(f"mapping_bias = {mapping_bias}")

    Parallel(n_jobs=n_jobs)(
        delayed(run)(epsilon, run_config)
        for epsilon in epsilons
    )
